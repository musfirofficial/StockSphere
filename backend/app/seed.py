def gen_phone(used: set) -> str:
    prefixes = ["070", "071", "072", "074", "075", "076", "077", "078"]
    while True:
        p = random.choice(prefixes)
        rest = f"{random.randint(0, 999):03d} {random.randint(0, 9999):04d}"
        phone = f"{p} {rest}"
        if phone not in used:
            used.add(phone)
            return phone


def gen_nic(used: set) -> str:
    while True:
        if random.random() < 0.5:
            nic = f"{random.randint(700000000, 999999999)}V"
        else:
            nic = f"{random.randint(199000000000, 200599999999)}"
        if nic not in used:
            used.add(nic)
            return nic


def gen_email(name: str, domain: str, used: set) -> str:
    base = name.lower().replace(" ", ".")
    email = f"{base}@{domain}"
    counter = 1
    while email in used:
        email = f"{base}{counter}@{domain}"
        counter += 1
    used.add(email)
    return email


