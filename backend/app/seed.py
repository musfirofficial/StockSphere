def gen_username(full_name: str, used: set) -> str:
    base = full_name.lower().replace(" ", ".")
    base = "".join(ch for ch in base if ch.isalnum() or ch in "._")
    username = base
    counter = 1
    while username in used:
        username = f"{base}{counter}"
        counter += 1
    used.add(username)
    return username


