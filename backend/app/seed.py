def hash_password(plain: str) -> str:
    """Hash directly with bcrypt, bypassing passlib's broken version-detection
    self-test against bcrypt 4.1+. Produces a standard $2b$ bcrypt hash string
    identical to what passlib's bcrypt scheme would produce."""
    return bcrypt.hashpw(plain.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


