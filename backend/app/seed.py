"""
app/seed.py

Generates realistic Sri Lankan dummy data for the hardware inventory system.

WHAT THIS DOES
--------------
- Runs only if the `categories` table is empty (anchor check) -> safe to
  restart the server repeatedly without duplicating or wiping edited data.
- Creates exactly ONE user: username "musfir", password "mustha" (bcrypt hashed
  via passlib, role=ADMIN).
- 25 hardware-related categories.
- 40 suppliers (7 inactive), Sri Lankan business names/addresses/phones.
- 150 items (22 inactive). ~60% of items with an open alert get restocked
  back above reorder_level by the end of their history; the rest are left
  genuinely low/out of stock right now, on purpose, so stock_alerts ends up
  with a realistic MIX of CRITICAL / LOW_STOCK / RESOLVED rows.
- ~1000 transactions, only for items that are active AND whose supplier is
  active. previous_quantity / new_quantity form a mathematically consistent
  chain per item (simulated forward, chronologically).
- StockAlert rows are generated by replaying the exact same state machine
  as your sync_stock_alert() service (CRITICAL/LOW_STOCK/RESOLVED
  transitions, single active alert per item, STOCK_OUT blocked while
  CRITICAL) - so alerts line up with the transaction history that caused
  them, not inserted independently.
- created_at is randomly scattered across the last 365 days for every table.
  updated_at == created_at everywhere (no edits have happened yet).
- Uses SQLAlchemy Core `insert()` with list-of-dicts (executemany), inserted
  in batches -> low memory, no per-row ORM object overhead.

REQUIREMENTS
------------
Uses the `bcrypt` package directly (already in your pyproject.toml).
passlib is NOT required by this script - it's skipped to avoid the known
passlib 1.7.4 vs bcrypt 4.1+ version-detection bug.

HOOK INTO FASTAPI STARTUP (app.py)
-----------------------------------
    from app.seed import seed_database

    @asynccontextmanager
    async def lifespan(_app: FastAPI):
        await create_db_and_tables()

        async with async_session_maker() as session:
            created = await AdminService.create_admin(session)
            ...

        await seed_database()   # <-- add this line

        yield
        await engine.dispose()

Adjust the `from app.models import ...` line below if your models file is
named differently.
"""

